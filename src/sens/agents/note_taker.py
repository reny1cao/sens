"""LLM-Powered Note-Taking Agent for Database Knowledge Management.

This agent uses LLMs to intelligently observe database interactions and maintain
organized notes about discoveries, similar to how a human database analyst
would document their exploration and findings.
"""

import json
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

import structlog
from openai import AsyncOpenAI

from sens.settings import get_settings

log = structlog.get_logger()


@dataclass
class DatabaseNote:
    """A single note about database knowledge."""

    timestamp: str
    category: str  # Generated by LLM: 'schema_discovery', 'data_insight', 'query_pattern', 'relationship', etc.
    title: str  # Generated by LLM: concise summary
    content: str  # Generated by LLM: detailed observation
    tables_involved: List[str]
    confidence: float  # LLM's confidence in the observation
    source: str  # 'exploration', 'query_execution', 'schema_analysis'
    tags: List[str]  # Generated by LLM: relevant keywords
    insights: List[str]  # Generated by LLM: key takeaways


@dataclass
class TableKnowledge:
    """What we know about a specific table."""

    name: str
    description: Optional[str] = None  # LLM-generated description
    purpose: Optional[str] = None  # LLM-inferred purpose
    columns: List[str] = None
    key_insights: List[str] = None  # LLM-generated insights
    data_patterns: List[str] = None  # LLM-observed patterns
    relationships: List[str] = None  # LLM-identified relationships
    row_count: Optional[int] = None
    last_updated: Optional[str] = None

    def __post_init__(self):
        if self.columns is None:
            self.columns = []
        if self.key_insights is None:
            self.key_insights = []
        if self.data_patterns is None:
            self.data_patterns = []
        if self.relationships is None:
            self.relationships = []


class LLMDatabaseNoteTaker:
    """LLM-powered agent that takes and organizes notes about database knowledge."""

    def __init__(self, notes_file: str = "database_notes.json"):
        """Initialize the LLM-powered note-taking agent."""
        self.notes_file = Path(notes_file)
        self.notes: List[DatabaseNote] = []
        self.table_knowledge: Dict[str, TableKnowledge] = {}
        self.settings = get_settings()

        # Initialize LLM client
        cfg = self.settings.get_openrouter_config()
        self.llm_client = AsyncOpenAI(
            base_url=cfg["base_url"],
            api_key=cfg["api_key"],
            default_headers={
                "HTTP-Referer": str(cfg["headers"]["HTTP-Referer"]),
                "X-Title": cfg["headers"]["X-Title"],
            },
        )

        self.load_notes()
        log.info("llm_note_taker_initialized", notes_file=str(self.notes_file))

    async def observe_database_interaction(
        self,
        interaction_type: str,
        query: str,
        results: Dict[str, Any],
        context: str = "",
    ) -> None:
        """Observe any database interaction and generate intelligent notes."""

        try:
            # Use LLM to analyze the interaction and generate notes
            analysis = await self._analyze_interaction_with_llm(
                interaction_type, query, results, context
            )

            if analysis and analysis.get("should_create_note", False):
                # Create note from LLM analysis
                note = DatabaseNote(
                    timestamp=datetime.now().isoformat(),
                    category=analysis.get("category", "general"),
                    title=analysis.get("title", "Database interaction"),
                    content=analysis.get("content", ""),
                    tables_involved=analysis.get("tables_involved", []),
                    confidence=analysis.get("confidence", 0.7),
                    source=interaction_type,
                    tags=analysis.get("tags", []),
                    insights=analysis.get("insights", []),
                )

                self.add_note(note)

                # Update table knowledge if relevant
                await self._update_table_knowledge(analysis)

        except Exception as e:
            log.error(
                "llm_analysis_failed", error=str(e), interaction_type=interaction_type
            )

    async def _analyze_interaction_with_llm(
        self, interaction_type: str, query: str, results: Dict[str, Any], context: str
    ) -> Optional[Dict[str, Any]]:
        """Use LLM to analyze database interaction and extract insights."""

        # Prepare context for LLM
        result_summary = self._summarize_results(results)
        existing_knowledge = self._get_relevant_knowledge_context(query)

        prompt = f"""You are an expert database analyst taking notes during database exploration.
Analyze this database interaction and determine if it contains valuable insights worth documenting.

INTERACTION DETAILS:
Type: {interaction_type}
Query: {query}
Results: {result_summary}
Context: {context}

EXISTING KNOWLEDGE:
{existing_knowledge}

ANALYSIS TASK:
1. Determine if this interaction reveals something noteworthy about the database structure, data patterns, or relationships
2. If noteworthy, extract key insights and categorize them appropriately
3. Generate a concise title and detailed content for the note
4. Identify relevant tables, tags, and confidence level

RESPONSE FORMAT (JSON):
{{
    "should_create_note": true/false,
    "category": "schema_discovery|data_insight|query_pattern|relationship|performance|data_quality",
    "title": "Concise, descriptive title",
    "content": "Detailed observation with specific findings",
    "tables_involved": ["table1", "table2"],
    "confidence": 0.0-1.0,
    "tags": ["relevant", "keywords"],
    "insights": ["key insight 1", "key insight 2"],
    "table_updates": {{
        "table_name": {{
            "description": "What this table appears to contain",
            "purpose": "Inferred business purpose",
            "patterns": ["observed data pattern"],
            "relationships": ["relationship to other tables"]
        }}
    }}
}}

Focus on:
- New schema discoveries (tables, columns, relationships)
- Data patterns and quality observations
- Performance insights
- Business logic inferences
- Unusual or interesting findings

Avoid creating notes for:
- Routine queries with expected results
- Duplicate information already documented
- Trivial or obvious observations"""

        try:
            response = await self.llm_client.chat.completions.create(
                model="google/gemini-2.0-flash-001",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.3,
                max_tokens=800,
            )

            content = response.choices[0].message.content.strip()

            # Extract JSON from response
            import re

            json_match = re.search(r"\{.*\}", content, re.DOTALL)
            if json_match:
                return json.loads(json_match.group(0))

            log.warning("no_json_in_llm_response", response_preview=content[:200])
            return None

        except Exception as e:
            log.error("llm_analysis_error", error=str(e))
            return None

    async def _update_table_knowledge(self, analysis: Dict[str, Any]) -> None:
        """Update table knowledge based on LLM analysis."""

        table_updates = analysis.get("table_updates", {})

        for table_name, updates in table_updates.items():
            if table_name not in self.table_knowledge:
                self.table_knowledge[table_name] = TableKnowledge(name=table_name)

            table_knowledge = self.table_knowledge[table_name]

            # Update with LLM insights
            if updates.get("description"):
                table_knowledge.description = updates["description"]
            if updates.get("purpose"):
                table_knowledge.purpose = updates["purpose"]
            if updates.get("patterns"):
                table_knowledge.data_patterns.extend(updates["patterns"])
                # Remove duplicates
                table_knowledge.data_patterns = list(set(table_knowledge.data_patterns))
            if updates.get("relationships"):
                table_knowledge.relationships.extend(updates["relationships"])
                table_knowledge.relationships = list(set(table_knowledge.relationships))

            table_knowledge.last_updated = datetime.now().isoformat()

    def _summarize_results(self, results: Dict[str, Any]) -> str:
        """Create a concise summary of query results for LLM analysis."""
        if not results:
            return "No results"

        summary_parts = []

        # Result count
        data = results.get("data", [])
        if isinstance(data, list):
            summary_parts.append(f"Returned {len(data)} rows")

        # Sample data (first few rows)
        if data and len(data) > 0:
            if len(data) <= 3:
                summary_parts.append(f"Sample data: {data}")
            else:
                summary_parts.append(f"Sample data (first 3): {data[:3]}")

        # Columns if available
        if "columns" in results:
            columns = results["columns"]
            if len(columns) <= 10:
                summary_parts.append(f"Columns: {columns}")
            else:
                summary_parts.append(
                    f"Columns ({len(columns)} total): {columns[:10]}..."
                )

        # Error information
        if results.get("error"):
            summary_parts.append(f"Error: {results['error']}")

        return " | ".join(summary_parts) if summary_parts else "Empty results"

    def _get_relevant_knowledge_context(self, query: str) -> str:
        """Get relevant existing knowledge for context."""
        context_parts = []

        # Find tables mentioned in query
        query_lower = query.lower()
        relevant_tables = [
            table
            for table in self.table_knowledge.keys()
            if table.lower() in query_lower
        ]

        # Add knowledge about relevant tables
        for table in relevant_tables[:3]:  # Limit to 3 tables
            knowledge = self.table_knowledge[table]
            table_info = [f"Table '{table}':"]
            if knowledge.description:
                table_info.append(f"  Description: {knowledge.description}")
            if knowledge.purpose:
                table_info.append(f"  Purpose: {knowledge.purpose}")
            if knowledge.columns:
                table_info.append(f"  Columns: {', '.join(knowledge.columns[:5])}")
            context_parts.append("\n".join(table_info))

        # Add recent relevant notes
        relevant_notes = self.search_notes(query)[:2]  # Top 2 relevant notes
        if relevant_notes:
            context_parts.append("Recent relevant notes:")
            for note in relevant_notes:
                context_parts.append(f"  - {note.title}: {note.content[:100]}...")

        return (
            "\n\n".join(context_parts)
            if context_parts
            else "No relevant existing knowledge"
        )

    async def get_knowledge_summary_with_llm(self) -> str:
        """Generate a natural language summary of accumulated knowledge using LLM."""

        if not self.notes and not self.table_knowledge:
            return "No database knowledge has been accumulated yet."

        # Prepare context
        recent_notes = self.get_recent_notes(10)
        table_summaries = []

        for table_name, knowledge in list(self.table_knowledge.items())[:5]:
            summary = f"Table '{table_name}'"
            if knowledge.description:
                summary += f": {knowledge.description}"
            if knowledge.purpose:
                summary += f" (Purpose: {knowledge.purpose})"
            table_summaries.append(summary)

        prompt = f"""You are a database analyst summarizing your exploration findings.
Create a natural, conversational summary of what you've learned about this database.

EXPLORATION DATA:
Total Notes: {len(self.notes)}
Tables Discovered: {len(self.table_knowledge)}

RECENT DISCOVERIES:
{chr(10).join([f"- {note.title}: {note.content[:100]}" for note in recent_notes[:5]])}

TABLE KNOWLEDGE:
{chr(10).join(table_summaries)}

Create a conversational summary (2-3 paragraphs) that captures:
1. What kind of database this appears to be
2. Key tables and their purposes
3. Interesting patterns or relationships discovered
4. Overall assessment of the data structure

Write as if you're briefing a colleague about your findings."""

        try:
            response = await self.llm_client.chat.completions.create(
                model="google/gemini-2.0-flash-001",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.4,
                max_tokens=500,
            )

            return response.choices[0].message.content.strip()

        except Exception as e:
            log.error("llm_summary_error", error=str(e))
            return f"Generated {len(self.notes)} notes about {len(self.table_knowledge)} tables during exploration."

    def add_note(self, note: DatabaseNote) -> None:
        """Add a new note to the collection."""
        self.notes.append(note)
        self.save_notes()
        log.info(
            "llm_note_added",
            category=note.category,
            title=note.title,
            confidence=note.confidence,
        )

    def get_notes_about_table(self, table: str) -> List[DatabaseNote]:
        """Get all notes related to a specific table."""
        return [note for note in self.notes if table in note.tables_involved]

    def get_notes_by_category(self, category: str) -> List[DatabaseNote]:
        """Get all notes in a specific category."""
        return [note for note in self.notes if note.category == category]

    def get_recent_notes(self, limit: int = 10) -> List[DatabaseNote]:
        """Get the most recent notes."""
        return sorted(self.notes, key=lambda n: n.timestamp, reverse=True)[:limit]

    def search_notes(self, query: str) -> List[DatabaseNote]:
        """Search notes by content, title, or tags."""
        query_lower = query.lower()
        scored_notes = []

        for note in self.notes:
            score = 0

            # Title match (highest weight)
            if query_lower in note.title.lower():
                score += 3

            # Content match
            if query_lower in note.content.lower():
                score += 2

            # Tag match
            for tag in note.tags:
                if query_lower in tag.lower():
                    score += 1

            # Table involvement
            for table in note.tables_involved:
                if query_lower in table.lower():
                    score += 2

            if score > 0:
                scored_notes.append((note, score))

        # Sort by score and return notes
        scored_notes.sort(key=lambda x: x[1], reverse=True)
        return [note for note, _ in scored_notes]

    def get_table_summary(self, table: str) -> Dict[str, Any]:
        """Get a summary of what we know about a table."""
        if table not in self.table_knowledge:
            return {"error": f"No knowledge about table '{table}'"}

        knowledge = self.table_knowledge[table]
        notes = self.get_notes_about_table(table)

        return {
            "table": table,
            "description": knowledge.description,
            "purpose": knowledge.purpose,
            "columns": knowledge.columns,
            "row_count": knowledge.row_count,
            "key_insights": knowledge.key_insights,
            "data_patterns": knowledge.data_patterns,
            "relationships": knowledge.relationships,
            "last_updated": knowledge.last_updated,
            "notes_count": len(notes),
            "recent_insights": [n.title for n in notes[-3:]],
        }

    def get_knowledge_summary(self) -> Dict[str, Any]:
        """Get a summary of all database knowledge."""
        categories = {}
        for note in self.notes:
            categories[note.category] = categories.get(note.category, 0) + 1

        return {
            "total_notes": len(self.notes),
            "tables_discovered": len(self.table_knowledge),
            "categories": categories,
            "tables": list(self.table_knowledge.keys()),
            "recent_activity": [n.title for n in self.get_recent_notes(5)],
            "avg_confidence": (
                sum(n.confidence for n in self.notes) / len(self.notes)
                if self.notes
                else 0
            ),
        }

    def save_notes(self) -> None:
        """Save notes to file."""
        try:
            data = {
                "notes": [asdict(note) for note in self.notes],
                "table_knowledge": {
                    name: asdict(knowledge)
                    for name, knowledge in self.table_knowledge.items()
                },
            }

            with open(self.notes_file, "w") as f:
                json.dump(data, f, indent=2)

        except Exception as e:
            log.error("failed_to_save_notes", error=str(e))

    def load_notes(self) -> None:
        """Load notes from file."""
        try:
            if self.notes_file.exists():
                with open(self.notes_file, "r") as f:
                    data = json.load(f)

                # Load notes
                self.notes = [
                    DatabaseNote(**note_data) for note_data in data.get("notes", [])
                ]

                # Load table knowledge
                self.table_knowledge = {
                    name: TableKnowledge(**knowledge_data)
                    for name, knowledge_data in data.get("table_knowledge", {}).items()
                }

                log.info(
                    "llm_notes_loaded",
                    count=len(self.notes),
                    tables=len(self.table_knowledge),
                )
        except Exception as e:
            log.error("failed_to_load_notes", error=str(e))
            self.notes = []
            self.table_knowledge = {}


# Backwards compatibility alias
DatabaseNoteTaker = LLMDatabaseNoteTaker
