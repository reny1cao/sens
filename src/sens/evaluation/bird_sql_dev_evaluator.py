#!/usr/bin/env python3
"""
BIRD-SQL-DEV Evaluation System.

Handles traditional text-to-SQL evaluation using SQLite databases with golden SQL comparison.
Separate from BIRD-CRITIC which uses PostgreSQL for SQL debugging tasks.
"""

import json
import sqlite3
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional

import structlog

from sens.agents.tool_registry import EvaluationContext
from sens.cli.agent_pipeline import AgentNL2SQLPipeline
from sens.exceptions import PipelineError
from sens.settings import get_settings

logger = structlog.get_logger(__name__)


@dataclass
class BirdSqlDevTask:
    """BIRD-SQL-DEV task representation."""

    question_id: str
    db_id: str
    question: str
    golden_sql: str
    evidence: Optional[str] = None
    difficulty: Optional[str] = None


@dataclass
class BirdSqlDevResult:
    """BIRD-SQL-DEV evaluation result."""

    question_id: str
    db_id: str
    question: str
    generated_sql: Optional[str]
    golden_sql: str
    execution_success: bool
    execution_error: Optional[str] = None
    result_count: Optional[int] = None
    execution_time_ms: Optional[float] = None

    # SQL comparison metrics
    exact_match: bool = False
    normalized_match: bool = False
    execution_match: bool = False

    # Metadata
    difficulty: Optional[str] = None
    evidence: Optional[str] = None


class BirdSqlDevEvaluator:
    """Evaluator for BIRD-SQL-DEV dataset using SQLite databases."""

    def __init__(
        self,
        database_dir: str = "external/BIRD-SQL-DEV/dev_databases",
        settings=None,
    ):
        """Initialize the BIRD-SQL-DEV evaluator.

        Args:
            database_dir: Directory containing SQLite database files
            settings: Application settings
        """
        self.database_dir = Path(database_dir)
        self.settings = settings or get_settings()
        self.tasks: List[BirdSqlDevTask] = []

        logger.info(
            f"Initialized BIRD-SQL-DEV evaluator with database dir: {self.database_dir}"
        )

    def load_tasks(self, json_path: str) -> None:
        """Load BIRD-SQL-DEV tasks from JSON file.

        Args:
            json_path: Path to the dev.json file
        """
        try:
            with open(json_path, "r") as f:
                data = json.load(f)

            self.tasks = []
            for item in data:
                task = BirdSqlDevTask(
                    question_id=str(item.get("question_id", "")),
                    db_id=item.get("db_id", ""),
                    question=item.get("question", ""),
                    golden_sql=item.get("SQL", ""),
                    evidence=item.get("evidence"),
                    difficulty=item.get("difficulty"),
                )
                self.tasks.append(task)

            logger.info(f"Loaded {len(self.tasks)} BIRD-SQL-DEV tasks")

        except Exception as e:
            raise PipelineError(f"Failed to load BIRD-SQL-DEV dataset: {e}")

    def _get_database_path(self, db_id: str) -> Path:
        """Get the SQLite database path for a given db_id.

        Args:
            db_id: Database identifier

        Returns:
            Path to the SQLite database file
        """
        # First try direct files in the database directory
        for ext in [".sqlite", ".db", ".sqlite3"]:
            db_path = self.database_dir / f"{db_id}{ext}"
            if db_path.exists():
                return db_path

        # Then try subdirectory structure (BIRD-SQL-DEV format)
        subdir_path = self.database_dir / db_id
        if subdir_path.exists() and subdir_path.is_dir():
            for ext in [".sqlite", ".db", ".sqlite3"]:
                db_path = subdir_path / f"{db_id}{ext}"
                if db_path.exists():
                    return db_path

        # If not found, return the direct .sqlite version (will fail later with clear error)
        return self.database_dir / f"{db_id}.sqlite"

    def _normalize_sql(self, sql: str) -> str:
        """Normalize SQL for comparison."""
        if not sql:
            return ""

        # Basic normalization
        normalized = sql.strip().lower()
        # Remove extra whitespace
        normalized = " ".join(normalized.split())
        # Remove trailing semicolon
        normalized = normalized.rstrip(";")

        return normalized

    def _compare_sql(self, generated_sql: str, golden_sql: str) -> Dict[str, bool]:
        """Compare generated SQL with golden SQL.

        Args:
            generated_sql: SQL generated by the system
            golden_sql: Golden SQL from the dataset

        Returns:
            Dictionary with comparison results
        """
        result = {
            "exact_match": False,
            "normalized_match": False,
        }

        if not generated_sql or not golden_sql:
            return result

        # Exact string match
        result["exact_match"] = generated_sql.strip() == golden_sql.strip()

        # Normalized match
        norm_generated = self._normalize_sql(generated_sql)
        norm_golden = self._normalize_sql(golden_sql)
        result["normalized_match"] = norm_generated == norm_golden

        return result

    def _execute_sql_on_sqlite(self, sql: str, db_path: Path) -> Dict[str, Any]:
        """Execute SQL on SQLite database.

        Args:
            sql: SQL query to execute
            db_path: Path to SQLite database

        Returns:
            Execution result dictionary
        """
        try:
            start_time = time.time()

            with sqlite3.connect(str(db_path)) as conn:
                conn.row_factory = sqlite3.Row  # Enable column access by name
                cursor = conn.cursor()
                cursor.execute(sql)

                # Fetch results
                rows = cursor.fetchall()
                columns = (
                    [description[0] for description in cursor.description]
                    if cursor.description
                    else []
                )

                # Convert rows to list of dictionaries
                data = []
                for row in rows:
                    data.append(dict(row))

                execution_time_ms = (time.time() - start_time) * 1000

                return {
                    "success": True,
                    "data": data,
                    "columns": columns,
                    "row_count": len(data),
                    "execution_time_ms": execution_time_ms,
                }

        except Exception as e:
            return {
                "success": False,
                "error": str(e),
                "execution_time_ms": (time.time() - start_time) * 1000,
            }

    def _check_execution_equivalence(
        self, generated_sql: str, golden_sql: str, db_path: Path
    ) -> bool:
        """Check if generated and golden SQL produce equivalent results.

        Args:
            generated_sql: SQL generated by the system
            golden_sql: Golden SQL from dataset
            db_path: Path to SQLite database

        Returns:
            True if both queries produce identical results
        """
        try:
            # Execute both queries
            gen_result = self._execute_sql_on_sqlite(generated_sql, db_path)
            gold_result = self._execute_sql_on_sqlite(golden_sql, db_path)

            # Both must succeed
            if not (gen_result["success"] and gold_result["success"]):
                return False

            # Compare result data (order-independent)
            gen_data = gen_result["data"]
            gold_data = gold_result["data"]

            # Convert to sets for order-independent comparison
            if isinstance(gen_data, list) and isinstance(gold_data, list):
                try:
                    gen_set = set(tuple(sorted(row.items())) for row in gen_data)
                    gold_set = set(tuple(sorted(row.items())) for row in gold_data)
                    return gen_set == gold_set
                except (TypeError, AttributeError):
                    # Fallback to exact list comparison
                    return gen_data == gold_data

            return gen_data == gold_data

        except Exception as e:
            logger.warning(f"Failed to check execution equivalence: {e}")
            return False

    async def evaluate_task_with_pipeline(
        self, task: BirdSqlDevTask, pipeline: AgentNL2SQLPipeline
    ) -> BirdSqlDevResult:
        """Evaluate a single BIRD-SQL-DEV task with provided pipeline for streaming."""
        logger.info(f"Evaluating task {task.question_id} for database {task.db_id}")

        # Get database path
        db_path = self._get_database_path(task.db_id)
        if not db_path.exists():
            return BirdSqlDevResult(
                question_id=task.question_id,
                db_id=task.db_id,
                question=task.question,
                generated_sql=None,
                golden_sql=task.golden_sql,
                execution_success=False,
                execution_error=f"Database file not found: {db_path}",
                difficulty=task.difficulty,
                evidence=task.evidence,
            )

        # Create question for SQLite evaluation
        detailed_question = f"""
BIRD-SQL-DEV EVALUATION TASK

USER QUESTION: {task.question}

EVIDENCE: {task.evidence or "No additional evidence provided"}

Task: Generate and execute a SQL query that answers the user's question.
"""

        try:
            # Use agent pipeline with SQLite tools - it will handle everything automatically
            result = await pipeline.process_question(detailed_question)

            # Extract results from agent pipeline
            if result is None:
                result = {"status": "error", "error": "Pipeline returned None result"}

            generated_sql = result.get("sql")
            execution_success = result.get("status") == "success"
            execution_error = result.get("error") if not execution_success else None
            result_count = result.get("row_count", 0)
            execution_time_ms = result.get("metadata", {}).get("total_duration_ms", 0.0)

        except Exception as e:
            logger.error(f"Agent pipeline evaluation failed: {e}")
            generated_sql = None
            execution_success = False
            execution_error = str(e)
            result_count = 0
            execution_time_ms = 0.0

        # Create evaluation result
        eval_result = BirdSqlDevResult(
            question_id=task.question_id,
            db_id=task.db_id,
            question=task.question,
            generated_sql=generated_sql,
            golden_sql=task.golden_sql,
            execution_success=execution_success,
            execution_error=execution_error,
            result_count=result_count,
            execution_time_ms=execution_time_ms,
            difficulty=task.difficulty,
            evidence=task.evidence,
        )

        # Compute additional metrics if SQL was generated successfully
        if generated_sql and task.golden_sql:
            eval_result = self._compute_additional_metrics(eval_result, db_path)

        return eval_result

    def _compute_additional_metrics(
        self, eval_result: BirdSqlDevResult, db_path: Path
    ) -> BirdSqlDevResult:
        """Compute additional metrics for BIRD-SQL-DEV evaluation.

        Args:
            eval_result: Current evaluation result
            db_path: Path to SQLite database

        Returns:
            Updated evaluation result with additional metrics
        """
        if not eval_result.generated_sql or not eval_result.golden_sql:
            return eval_result

        # SQL comparison metrics
        sql_comparison = self._compare_sql(
            eval_result.generated_sql, eval_result.golden_sql
        )
        eval_result.exact_match = sql_comparison["exact_match"]
        eval_result.normalized_match = sql_comparison["normalized_match"]

        # Execution equivalence check
        if db_path.exists():
            eval_result.execution_match = self._check_execution_equivalence(
                eval_result.generated_sql, eval_result.golden_sql, db_path
            )
        else:
            eval_result.execution_match = False

        return eval_result

    async def evaluate_task(
        self, task: BirdSqlDevTask, event_callback=None
    ) -> BirdSqlDevResult:
        """Evaluate a single BIRD-SQL-DEV task.

        Args:
            task: Task to evaluate

        Returns:
            Evaluation result
        """
        # Get database path for SQLite context
        db_path = self._get_database_path(task.db_id)

        # Create pipeline for this specific task with SQLite context
        pipeline = AgentNL2SQLPipeline(
            metrics_enabled=False,
            debug_mode=True,
            max_iterations=5,  # Allow multiple iterations for reasoning
            event_callback=event_callback,  # Pass event callback for streaming
            evaluation_context=EvaluationContext.BIRD_SQL_DEV,
            db_path=str(db_path),
        )

        # Use the pipeline-based evaluation method
        return await self.evaluate_task_with_pipeline(task, pipeline)

    async def evaluate_all(self, limit: Optional[int] = None) -> List[BirdSqlDevResult]:
        """Evaluate all loaded tasks.

        Args:
            limit: Optional limit on number of tasks to evaluate

        Returns:
            List of evaluation results
        """
        tasks_to_evaluate = self.tasks[:limit] if limit else self.tasks
        results = []

        total_tasks = len(tasks_to_evaluate)
        logger.info(f"Starting evaluation of {total_tasks} BIRD-SQL-DEV tasks")

        for i, task in enumerate(tasks_to_evaluate, 1):
            logger.info(f"Progress: {i}/{total_tasks} - {task.db_id}")
            result = await self.evaluate_task(task)
            results.append(result)

        return results

    def calculate_metrics(self, results: List[BirdSqlDevResult]) -> Dict[str, Any]:
        """Calculate evaluation metrics.

        Args:
            results: List of evaluation results

        Returns:
            Dictionary with metrics
        """
        if not results:
            return {}

        total_tasks = len(results)

        # Basic success metrics
        execution_success = sum(1 for r in results if r.execution_success)
        exact_matches = sum(1 for r in results if r.exact_match)
        normalized_matches = sum(1 for r in results if r.normalized_match)
        execution_matches = sum(1 for r in results if r.execution_match)

        metrics = {
            "total_tasks": total_tasks,
            "execution_success_rate": execution_success / total_tasks,
            "success_rate": execution_success / total_tasks,  # Frontend compatibility
            "exact_match_rate": exact_matches / total_tasks,
            "execution_accuracy": exact_matches / total_tasks,  # Frontend compatibility
            "normalized_match_rate": normalized_matches / total_tasks,
            "execution_match_rate": execution_matches / total_tasks,
        }

        # Difficulty breakdown
        difficulties = {}
        for result in results:
            if result.difficulty:
                if result.difficulty not in difficulties:
                    difficulties[result.difficulty] = {
                        "total": 0,
                        "success": 0,
                        "exact_match": 0,
                    }
                difficulties[result.difficulty]["total"] += 1
                if result.execution_success:
                    difficulties[result.difficulty]["success"] += 1
                if result.exact_match:
                    difficulties[result.difficulty]["exact_match"] += 1

        # Calculate rates for each difficulty
        for difficulty, stats in difficulties.items():
            if stats["total"] > 0:
                stats["success_rate"] = stats["success"] / stats["total"]
                stats["exact_match_rate"] = stats["exact_match"] / stats["total"]

        metrics["difficulty_breakdown"] = difficulties

        # Execution time metrics
        execution_times = [
            r.execution_time_ms for r in results if r.execution_time_ms is not None
        ]
        if execution_times:
            metrics["avg_execution_time_ms"] = sum(execution_times) / len(
                execution_times
            )
            metrics["max_execution_time_ms"] = max(execution_times)

        return metrics

    def save_results(self, results: List[BirdSqlDevResult], output_path: str) -> None:
        """Save evaluation results to JSON file.

        Args:
            results: List of evaluation results
            output_path: Path to save results
        """
        output_data = []

        for result in results:
            result_dict = {
                "question_id": result.question_id,
                "db_id": result.db_id,
                "question": result.question,
                "generated_sql": result.generated_sql,
                "golden_sql": result.golden_sql,
                "execution_success": result.execution_success,
                "execution_error": result.execution_error,
                "result_count": result.result_count,
                "execution_time_ms": result.execution_time_ms,
                "exact_match": result.exact_match,
                "normalized_match": result.normalized_match,
                "execution_match": result.execution_match,
                "difficulty": result.difficulty,
                "evidence": result.evidence,
            }
            output_data.append(result_dict)

        # Save results
        with open(output_path, "w") as f:
            json.dump(output_data, f, indent=2)

        # Save metrics
        metrics = self.calculate_metrics(results)
        metrics_path = output_path.replace(".json", "_metrics.json")
        with open(metrics_path, "w") as f:
            json.dump(metrics, f, indent=2)

        logger.info(f"Saved BIRD-SQL-DEV results to {output_path}")
        logger.info(f"Saved BIRD-SQL-DEV metrics to {metrics_path}")
